-- Nazwy UPPERCASE bez cudzysłowów (Postgres zapisze je jako lowercase, działa case-insensitive).

CREATE TABLE MISJE (
  MISJA_ID_MOJE_PK  BIGINT GENERATED BY DEFAULT AS IDENTITY,
  MISJA_ID_Z_GRY    BIGINT,
  MISJA_URL_WIKI    VARCHAR(400) NOT NULL,
  MISJA_URL_WOWHEAD VARCHAR(400),
  MISJA_TYTUL_EN    VARCHAR(500) NOT NULL,
  MISJA_TYTUL_PL    VARCHAR(500),
  STATUS_MISJI      SMALLINT,

  NAZWA_LINII_FABULARNEJ_EN  VARCHAR(255),
  NAZWA_LINII_FABULARNEJ_PL  VARCHAR(255),
  KOLEJNOSC_LINII_FABULARNEJ INT,

  KONTYNENT_EN VARCHAR(100),
  KRAINA_EN    VARCHAR(155),
  DODATEK_EN   VARCHAR(55),
  KONTYNENT_PL VARCHAR(100),
  KRAINA_PL    VARCHAR(155),
  DODATEK_PL   VARCHAR(55),

  DODANO_W_PATCHU VARCHAR(55),

  MISJA_TYTUL_NASTEPNA_EN   VARCHAR(500),
  MISJA_TYTUL_POPRZEDNIA_EN VARCHAR(500),
  WYMAGANY_LVL  INT,
  NPC_START_ID  BIGINT,
  NPC_KONIEC_ID BIGINT,
  DATA_DODANIA  TIMESTAMPTZ NOT NULL DEFAULT now(),
  DATA_UPDATE   TIMESTAMPTZ DEFAULT now(),

  HASH_EN CHAR(16),
  WSKAZNIK_ZGODNOSCI DECIMAL(10, 4),

  CONSTRAINT PK_MISJE PRIMARY KEY (MISJA_ID_MOJE_PK),
  CONSTRAINT UX_MISJE_URL_WIKI UNIQUE (MISJA_URL_WIKI),
  CONSTRAINT FK_MISJE_NPC_START  FOREIGN KEY (NPC_START_ID)  REFERENCES NPC(NPC_ID_MOJE_PK),
  CONSTRAINT FK_MISJE_NPC_KONIEC FOREIGN KEY (NPC_KONIEC_ID) REFERENCES NPC(NPC_ID_MOJE_PK)
);
