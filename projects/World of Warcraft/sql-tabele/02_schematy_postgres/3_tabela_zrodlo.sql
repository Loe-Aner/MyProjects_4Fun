-- Tabela ZRODLO_MISJE — wersja PostgreSQL (konwersja z SQL Server)
-- Nazwy UPPERCASE bez cudzysłowów. HTML_SKOMPRESOWANY = tekst (zlib+base64) -> TEXT.

CREATE TABLE ZRODLO_MISJE (
  TECH_ID BIGINT GENERATED BY DEFAULT AS IDENTITY,

  MISJA_ID_MOJE_FK BIGINT NOT NULL,

  ZRODLO_NAZWA VARCHAR(20) NOT NULL
    CHECK (ZRODLO_NAZWA IN ('wiki', 'wowhead', 'wowdb', 'recznie', 'z addonu')),

  RODZAJ VARCHAR(20) NOT NULL DEFAULT 'MISJA',

  DATA_WYSCRAPOWANIA TIMESTAMPTZ NOT NULL DEFAULT now(),

  HTML_HASH_GLOWNY_CEL    CHAR(64),
  HTML_HASH_PODRZEDNY_CEL CHAR(64),
  HTML_HASH_TRESC         CHAR(64),
  HTML_HASH_POSTEP        CHAR(64),
  HTML_HASH_ZAKONCZENIE   CHAR(64),
  HTML_HASH_NAGRODY       CHAR(64),
  HTML_HASH_DYMKI         CHAR(64),
  HTML_HASH_GOSSIP        CHAR(64),
  HTML_SKOMPRESOWANY      TEXT,

  CONSTRAINT PK_ZRODLO_MISJE PRIMARY KEY (TECH_ID),
  CONSTRAINT FK_ZRODLO_MISJE_MISJE
    FOREIGN KEY (MISJA_ID_MOJE_FK) REFERENCES MISJE(MISJA_ID_MOJE_PK)
);

CREATE INDEX IX_ZRODLO_MISJE_MISJA
  ON ZRODLO_MISJE (MISJA_ID_MOJE_FK, DATA_WYSCRAPOWANIA DESC);
